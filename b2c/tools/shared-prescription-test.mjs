import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../../krane-golden-fixture.js',import.meta.url),'utf8');
const saved=new Map(), events=[];
function boot(){
 const context={localStorage:{getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)},window:{dispatchEvent:e=>events.push(e)},CustomEvent:class{constructor(type,options){this.type=type;this.detail=options.detail;}}};
 vm.runInNewContext(source,context);return context.window.KraneGoldenDemo;
}
let demo=boot();
const previous=demo.readState();
const item={name:'Synthetic QA item',sku:'QA-ONLY',price:17.5,qty:3,directions:'Exact fixture instructions',dir:'Fixture EN',dirTH:'Fixture TH'};
demo.writePrescription({items:[item],total:999999});
assert.equal(demo.readState().prescription.total,52.5,'total comes from item prices, not supplied total');
assert.equal(demo.readState().fulfilmentStatus,previous.fulfilmentStatus,'sending plan must not advance fulfillment');
item.name='Mutated caller';
assert.equal(demo.readState().prescription.items[0].name,'Synthetic QA item','copy isolates caller mutation');
assert.equal(events.at(-1).type,'krane-demo-state');
demo=boot();
assert.equal(demo.readState().prescription.items[0].directions,'Exact fixture instructions','reload preserves clinical text');
assert.equal(demo.readState().prescription.items[0].qty,3);
for(const bad of [{items:[]},{items:[{...item,qty:0}]},{items:[{...item,qty:1.5}]},{items:[{...item,price:-1}]},{items:[{...item,price:Infinity}]},{items:[{...item,name:' '}]}])assert.throws(()=>demo.writePrescription(bad));
assert.equal(demo.readState().prescription.total,52.5,'rejected input does not corrupt stored prescription');
demo.writeState({fulfilmentStatus:'Delivered'});
assert.equal(demo.readState().prescription.total,52.5,'other state updates preserve payload');
demo.reset();
assert.equal(demo.readState().prescription,null,'reset removes previous prescription');
saved.set('krane-golden-demo-state-v1','not json');
assert.equal(boot().readState().prescription,null,'corrupt browser storage recovers safely');
console.log('PASS shared prescription persistence, payload validation, totals, reset, events, and fulfillment isolation');
